#!/usr/bin/env node
// Builds the Solar Icons SVG sprite and the shared icon map module.
//
//   node scripts/build-sprite.mjs
//
// Source of truth: scripts/icon-map.json (Discourse/Font Awesome icon name =>
// Solar icon name). The sprite ids are `si-<solar>-<style>`, so the runtime
// initializer only has to pick a style suffix.
//
// Icon data is read from the pinned @solar-icons/static release and cached in
// scripts/.cache so repeat builds are offline.

import { mkdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SOLAR_VERSION = "2.3.4";
const SOLAR_CDN = `https://cdn.jsdelivr.net/npm/@solar-icons/static@${SOLAR_VERSION}`;

// Styles baked into the sprite. Keep in sync with settings.yml (icon_style).
const STYLES = ["linear", "bold"];

// Discourse refuses theme sprites above 1 MB (SvgSprite::MAX_THEME_SPRITE_SIZE).
const MAX_SPRITE_BYTES = 1024 * 1024;
const WARN_SPRITE_BYTES = 900 * 1024;

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const componentDir = path.resolve(scriptDir, "..");
const cacheDir = path.join(scriptDir, ".cache");
const mapPath = path.join(scriptDir, "icon-map.json");
const spritePath = path.join(componentDir, "assets", "icons-sprite.svg");
const modulePath = path.join(
  componentDir,
  "javascripts",
  "discourse",
  "lib",
  "solar-icon-map.js",
);

async function exists(file) {
  try {
    await stat(file);
    return true;
  } catch {
    return false;
  }
}

async function loadIconData() {
  await mkdir(cacheDir, { recursive: true });
  const cachePath = path.join(cacheDir, `icons-${SOLAR_VERSION}.json`);

  if (await exists(cachePath)) {
    return JSON.parse(await readFile(cachePath, "utf8"));
  }

  console.log(`Downloading Solar Icons ${SOLAR_VERSION} from the CDN...`);
  const response = await fetch(`${SOLAR_CDN}/dist/icons.json`);
  if (!response.ok) {
    throw new Error(
      `Could not download icons.json (HTTP ${response.status}). ` +
        `Check the network or install @solar-icons/static@${SOLAR_VERSION} manually.`,
    );
  }

  const body = await response.text();
  await writeFile(cachePath, body);
  return JSON.parse(body);
}

// Turns a standalone Solar SVG into a <symbol> that can be referenced with
// <use href="#si-home-linear">. Presentation attributes live on the symbol so
// paths that do not set them (the linear style) still render.
function toSymbol(svg, solarName, style) {
  const inner = svg
    .slice(svg.indexOf(">") + 1, svg.lastIndexOf("</svg>"))
    .trim();

  return (
    `<symbol id="si-${solarName}-${style}" viewBox="0 0 24 24" ` +
    `fill="none" stroke-linecap="round" ` +
    `stroke-linejoin="round" class="solar solar-${solarName}-${style}">` +
    `${inner}</symbol>`
  );
}

function buildSprite(iconMap, iconData) {
  const solarNames = [...new Set(Object.values(iconMap))].sort();
  const missing = [];

  for (const solarName of solarNames) {
    for (const style of STYLES) {
      if (!iconData[`${solarName}-${style}`]) {
        missing.push(`${solarName}-${style}`);
      }
    }
  }

  if (missing.length) {
    throw new Error(
      `Unknown Solar icons in scripts/icon-map.json:\n  ${missing.join("\n  ")}`,
    );
  }

  const symbols = [];
  for (const style of STYLES) {
    for (const solarName of solarNames) {
      symbols.push(toSymbol(iconData[`${solarName}-${style}`], solarName, style));
    }
  }

  const sprite = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    "<!--",
    "  Solar Icons (https://solar-icons.dev) by 480 Design, licensed CC BY 4.0.",
    `  Generated from @solar-icons/static@${SOLAR_VERSION} by scripts/build-sprite.mjs.`,
    "  Do not edit by hand; regenerate instead.",
    "-->",
    '<svg xmlns="http://www.w3.org/2000/svg" style="display: none;">',
    ...symbols.map((symbol) => `  ${symbol}`),
    "</svg>",
    "",
  ].join("\n");

  return { sprite, solarNames };
}

function buildMapModule(iconMap) {
  const entries = Object.keys(iconMap)
    .sort()
    .map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(iconMap[key])},`);

  return [
    "// Generated by scripts/build-sprite.mjs from scripts/icon-map.json.",
    "// Do not edit by hand; change the JSON and rebuild.",
    "",
    "export const ICON_MAP = Object.freeze({",
    ...entries,
    "});",
    "",
  ].join("\n");
}

const iconMap = JSON.parse(await readFile(mapPath, "utf8"));
const iconData = await loadIconData();
const { sprite, solarNames } = buildSprite(iconMap, iconData);
const spriteBytes = Buffer.byteLength(sprite);

if (spriteBytes > MAX_SPRITE_BYTES) {
  throw new Error(
    `Sprite is ${(spriteBytes / 1024).toFixed(0)} KB; Discourse allows 1024 KB. ` +
      `Drop a style from STYLES or trim scripts/icon-map.json.`,
  );
}

await mkdir(path.dirname(spritePath), { recursive: true });
await mkdir(path.dirname(modulePath), { recursive: true });
await writeFile(spritePath, sprite);
await writeFile(modulePath, buildMapModule(iconMap));

const warning =
  spriteBytes > WARN_SPRITE_BYTES
    ? ` (warning: close to the ${MAX_SPRITE_BYTES / 1024} KB limit)`
    : "";

console.log(
  `Wrote ${path.relative(componentDir, spritePath)}: ` +
    `${solarNames.length} icons x ${STYLES.length} styles ` +
    `(${STYLES.join(", ")}), ${(spriteBytes / 1024).toFixed(0)} KB${warning}`,
);
console.log(
  `Wrote ${path.relative(componentDir, modulePath)}: ` +
    `${Object.keys(iconMap).length} icon mappings`,
);
